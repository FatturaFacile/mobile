/// The locale tables, exposed so a unit test can check that each one defines every [RB].
const Map<String, Map<RB, String>> supplierRebatesLocaleTables =
    <String, Map<RB, String>>{'it': _it, 'en': _en, 'de': _de, 'fr': _fr};

/// Localized labels of the supplier rebates screens; unknown languages fall back to English, and a region tag
/// (`de-CH`, `it_IT`) selects its language.
class SupplierRebatesStrings {
  const SupplierRebatesStrings(this.languageCode);

  final String languageCode;

  /// `de-CH` / `it_IT` / `FR` to `de` / `it` / `fr`.
  String get language => languageCode.split(RegExp('[-_]')).first.toLowerCase();

  String call(RB key) =>
      (supplierRebatesLocaleTables[language] ?? _en)[key] ?? _en[key] ?? '';

  String rebateType(RebateType type) => switch (type) {
    RebateType.tieredVolume => call(RB.typeTieredVolume),
    RebateType.fixedBonus => call(RB.typeFixedBonus),
    RebateType.marketingContribution => call(RB.typeMarketing),
  };

  String tierMode(TierMode mode) => switch (mode) {
    TierMode.retroactive => call(RB.modeRetroactive),
    TierMode.incremental => call(RB.modeIncremental),
  };

  String agreementStatus(AgreementStatus status) => switch (status) {
    AgreementStatus.draft => call(RB.statusDraft),
    AgreementStatus.active => call(RB.statusActive),
    AgreementStatus.closed => call(RB.statusClosed),
    AgreementStatus.cancelled => call(RB.statusCancelled),
  };

  String proposalStatus(ProposalStatus status) => switch (status) {
    ProposalStatus.draft => call(RB.settlementDraft),
    ProposalStatus.pendingApproval => call(RB.settlementPendingApproval),
    ProposalStatus.approved => call(RB.settlementApproved),
    ProposalStatus.settled => call(RB.settlementSettled),
    ProposalStatus.cancelled => call(RB.settlementCancelled),
  };

  String executionMode(ExecutionMode mode) => switch (mode) {
    ExecutionMode.creditNoteRequest => call(RB.execCreditNoteRequest),
    ExecutionMode.chargeInvoice => call(RB.execChargeInvoice),
    ExecutionMode.apSetOff => call(RB.execApSetOff),
  };

  String lineType(ProposalLineType type) => switch (type) {
    ProposalLineType.invoice => call(RB.lineInvoice),
    ProposalLineType.creditNote => call(RB.lineCreditNote),
    ProposalLineType.contribution => call(RB.lineContribution),
    ProposalLineType.bonus => call(RB.lineBonus),
  };

  String contributionKind(String kind) => switch (kind) {
    'marketing' => call(RB.kindMarketing),
    'co_marketing' => call(RB.kindCoMarketing),
    'listing' => call(RB.kindListing),
    _ => kind,
  };

  String contributionStatus(ContributionStatus status) => switch (status) {
    ContributionStatus.planned => call(RB.contribPlanned),
    ContributionStatus.accrued => call(RB.contribAccrued),
    ContributionStatus.settled => call(RB.contribSettled),
  };

  String runStatus(RunStatus status) => switch (status) {
    RunStatus.posted => call(RB.runPosted),
    RunStatus.reversed => call(RB.runReversed),
  };

  String frequencyName(String? frequency) => switch (frequency) {
    'monthly' => call(RB.freqMonthly),
    'quarterly' => call(RB.freqQuarterly),
    'custom' => call(RB.freqCustom),
    _ => '',
  };

  String action(ProposalAction action) => switch (action) {
    ProposalAction.submit => call(RB.submit),
    ProposalAction.approve => call(RB.approve),
    ProposalAction.cancel => call(RB.cancel),
  };

  String confirm(ProposalAction action) => switch (action) {
    ProposalAction.submit => call(RB.confirmSubmit),
    ProposalAction.approve => call(RB.confirmApprove),
    ProposalAction.cancel => call(RB.confirmCancel),
  };

  String alert(BalanceAlertCode code) => switch (code) {
    BalanceAlertCode.ceilingNear => call(RB.alertCeilingNear),
    BalanceAlertCode.ceilingExceeded => call(RB.alertCeilingExceeded),
    BalanceAlertCode.minimumAtRisk => call(RB.alertMinimumAtRisk),
    BalanceAlertCode.minimumNotMet => call(RB.alertMinimumNotMet),
  };

  String error(RebateException e) => switch (e.kind) {
    RebateErrorKind.forbidden => call(RB.errorForbidden),
    RebateErrorKind.notFound => call(RB.errorNotFound),
    RebateErrorKind.offline => call(RB.errorOffline),
    RebateErrorKind.invalid =>
      e.detail.isEmpty ? call(RB.errorInvalid) : e.detail,
    RebateErrorKind.unknown => call(RB.errorUnknown),
  };
}
