/// The locale tables, exposed so a unit test can check that each one defines every [RS].
const Map<String, Map<RS, String>> resourcePlanningLocaleTables =
    <String, Map<RS, String>>{'it': _it, 'en': _en, 'de': _de, 'fr': _fr};

/// Localized labels of the resource planning screens; unknown languages fall back to English. Regional codes such as
/// `de-CH`, `fr_CH`, `it-IT` resolve to their language.
class ResourcePlanningStrings {
  const ResourcePlanningStrings(this.languageCode);

  final String languageCode;

  String get _language => languageCode.split(RegExp('[-_]')).first.toLowerCase();

  String call(RS key, {Map<String, Object> params = const <String, Object>{}}) {
    final String template =
        (resourcePlanningLocaleTables[_language] ?? _en)[key] ??
        _en[key] ??
        '';
    return params.entries.fold<String>(
      template,
      (String text, MapEntry<String, Object> p) =>
          text.replaceAll('{${p.key}}', '${p.value}'),
    );
  }

  /// Label of a candidate blocker code; unknown codes are shown as received.
  String blocker(String code) => switch (code) {
    'skill_missing' => call(RS.blockerSkillMissing),
    'proficiency_too_low' => call(RS.blockerProficiencyTooLow),
    'skill_expired' => call(RS.blockerSkillExpired),
    'certificate_missing' => call(RS.blockerCertificateMissing),
    'certificate_expired' => call(RS.blockerCertificateExpired),
    'insufficient_availability' => call(RS.blockerInsufficientAvailability),
    _ => code,
  };

  /// Label of a domain violation code; unknown codes are shown as received.
  String violation(String code) => switch (code) {
    'already_hard_committed' => call(RS.violationAlreadyHard),
    'project_not_allocatable' => call(RS.violationProjectNotAllocatable),
    'overload' => call(RS.violationOverload),
    'invalid_period' => call(RS.violationInvalidPeriod),
    'no_working_days' => call(RS.violationNoWorkingDays),
    'hard_booking_requires_project' => call(RS.violationHardNeedsProject),
    'skill_certificate_invalid' => call(RS.violationSkillCertificate),
    'employee_not_found' => call(RS.violationEmployeeNotFound),
    'wbs_node_not_in_project' => call(RS.violationWbsNotInProject),
    'opportunity_not_open' => call(RS.violationOpportunityNotOpen),
    'soft_booking_requires_reference' => call(RS.violationSoftNeedsReference),
    'certification_code_required' => call(RS.violationCertCodeRequired),
    // Warning codes of an allocation mutation share the labels of the candidate blockers.
    'skill_missing' ||
    'proficiency_too_low' ||
    'skill_expired' ||
    'certificate_missing' ||
    'certificate_expired' => blocker(code),
    _ => code,
  };
}
