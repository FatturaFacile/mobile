/// The locale tables, exposed so a unit test can check that each one defines every [HL].
const Map<String, Map<HL, String>> helpdeskLocaleTables =
    <String, Map<HL, String>>{'it': _it, 'en': _en, 'de': _de, 'fr': _fr};

/// Localized labels of the helpdesk screens; unknown languages fall back to English.
class HelpdeskStrings {
  const HelpdeskStrings(this.languageCode);

  final String languageCode;

  String call(HL key) =>
      (helpdeskLocaleTables[languageCode] ?? _en)[key] ?? _en[key] ?? '';

  String slaTarget(SlaTargetKind kind) => switch (kind) {
    SlaTargetKind.response => call(HL.slaResponse),
    SlaTargetKind.nextUpdate => call(HL.slaNextUpdate),
    SlaTargetKind.resolution => call(HL.slaResolution),
  };

  String billing(BillingStatus status) => switch (status) {
    BillingStatus.contractDeducted => call(HL.billingContractDeducted),
    BillingStatus.partiallyDeducted => call(HL.billingPartiallyDeducted),
    BillingStatus.billablePending => call(HL.billingBillablePending),
    BillingStatus.nonBillable => call(HL.billingNonBillable),
    BillingStatus.unknown => '',
  };

  /// `due in 12m` / `overdue by 1h 05m` for the countdown of one SLA clock.
  String countdown(Duration remaining) => remaining.isNegative
      ? '${call(HL.overdueBy)} ${formatCountdown(-remaining)}'
      : '${call(HL.dueIn)} ${formatCountdown(remaining)}';

  /// Title of a push alert.
  String pushTitle(bool isSla, bool breach) => !isSla
      ? call(HL.pushAssigned)
      : (breach ? call(HL.pushSlaBreach) : call(HL.pushSlaWarning));

  String error(HelpdeskException e) => switch (e.kind) {
    HelpdeskErrorKind.forbidden => call(HL.errorForbidden),
    HelpdeskErrorKind.notFound => call(HL.errorNotFound),
    HelpdeskErrorKind.offline => call(HL.errorOffline),
    HelpdeskErrorKind.invalid =>
      e.detail.isEmpty ? call(HL.errorInvalid) : e.detail,
    HelpdeskErrorKind.unknown => call(HL.errorUnknown),
  };
}
