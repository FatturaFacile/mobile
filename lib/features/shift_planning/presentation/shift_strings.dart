/// The locale tables, exposed so a unit test can check that each one defines every [SL].
const Map<String, Map<SL, String>> shiftLocaleTables =
    <String, Map<SL, String>>{'it': _it, 'en': _en, 'de': _de, 'fr': _fr};

/// Localized labels of the shift planning screens; unknown languages fall back to English.
class ShiftStrings {
  const ShiftStrings(this.languageCode);

  final String languageCode;

  String call(SL key) =>
      (shiftLocaleTables[languageCode] ?? _en)[key] ?? _en[key] ?? '';

  String tag(String wire) => switch (wire) {
    'night' => call(SL.tagNight),
    'sunday' => call(SL.tagSunday),
    'holiday' => call(SL.tagHoliday),
    'on_call' => call(SL.tagOnCall),
    _ => wire,
  };
}
