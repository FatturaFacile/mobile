  const ProjectPortfolioStrings._(this._table);

  final Map<PP, String> _table;

  /// The labels for the language of [context]; unknown languages fall back to English.
  factory ProjectPortfolioStrings.of(BuildContext context) =>
      ProjectPortfolioStrings.forLanguage(
        Localizations.localeOf(context).languageCode,
      );

  factory ProjectPortfolioStrings.forLanguage(String language) {
    final String code = language.split(RegExp('[-_]')).first.toLowerCase();
    return ProjectPortfolioStrings._(tables[code] ?? tables['en']!);
  }

  String t(PP key) => _table[key]!;

  /// A label with `{name}` placeholders replaced.
  String f(PP key, Map<String, Object> values) {
    String text = t(key);
    values.forEach((String name, Object value) {
      text = text.replaceAll('{$name}', '$value');
    });
    return text;
  }

