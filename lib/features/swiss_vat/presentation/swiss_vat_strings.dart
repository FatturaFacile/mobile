/// Resolves translations explicitly across `it-CH`, `it-IT`, `de-CH`, `fr-CH`, and `en`.
class SwissVatStrings {
  const SwissVatStrings(this.localeTag);

  final String localeTag;

  String get normalizedLocale {
    final String clean = localeTag.trim().replaceAll('_', '-');
    if (swissVatLocaleTables.containsKey(clean)) {
      return clean;
    }
    final String lower = clean.toLowerCase();
    if (lower.startsWith('de')) {
      return 'de-CH';
    }
    if (lower.startsWith('fr')) {
      return 'fr-CH';
    }
    if (lower == 'it-it') {
      return 'it-IT';
    }
    if (lower.startsWith('it')) {
      return 'it-CH';
    }
    return 'en';
  }

  Map<SV, String> get _table => swissVatLocaleTables[normalizedLocale] ?? _en;

  String call(SV key) => _table[key] ?? _en[key]!;

  String error(SwissVatException e) => switch (e.kind) {
    SwissVatErrorKind.forbidden => call(SV.forbidden),
    SwissVatErrorKind.offline => call(SV.offlineBanner),
    _ => e.detail.isNotEmpty ? e.detail : call(SV.loadError),
  };

  String adjustmentLabel(InputTaxAdjustmentType type) {
    final String lang = normalizedLocale.split('-').first;
    return switch ((lang, type)) {
      ('it', InputTaxAdjustmentType.autoconsumo) => 'Autoconsumo (Art. 31 LIVA)',
      ('it', InputTaxAdjustmentType.degrassazione) => 'Degrassazione (Art. 32 LIVA)',
      ('it', InputTaxAdjustmentType.mixedUseReduction) => 'Uso misto (Art. 30 LIVA)',
      ('it', InputTaxAdjustmentType.subsidyReduction) => 'Sussidi (Art. 33 cpv. 2 LIVA)',
      ('de', InputTaxAdjustmentType.autoconsumo) => 'Eigenverbrauch (Art. 31 MWSTG)',
      ('de', InputTaxAdjustmentType.degrassazione) => 'Einlageentsteuerung (Art. 32 MWSTG)',
      ('de', InputTaxAdjustmentType.mixedUseReduction) => 'Vorsteuerkürzung (Art. 30 MWSTG)',
      ('de', InputTaxAdjustmentType.subsidyReduction) => 'Subventionen (Art. 33 Abs. 2 MWSTG)',
      ('fr', InputTaxAdjustmentType.autoconsumo) => 'Prestations à soi-même (Art. 31 LTVA)',
      ('fr', InputTaxAdjustmentType.degrassazione) => 'Dégrèvement ultérieur (Art. 32 LTVA)',
      ('fr', InputTaxAdjustmentType.mixedUseReduction) => 'Double affectation (Art. 30 LTVA)',
      ('fr', InputTaxAdjustmentType.subsidyReduction) => 'Subventions (Art. 33 al. 2 LTVA)',
      (_, InputTaxAdjustmentType.autoconsumo) => 'Self-consumption (Art. 31 VAT Act)',
      (_, InputTaxAdjustmentType.degrassazione) => 'Subsequent deduction (Art. 32 VAT Act)',
      (_, InputTaxAdjustmentType.mixedUseReduction) => 'Mixed-use reduction (Art. 30 VAT Act)',
      (_, InputTaxAdjustmentType.subsidyReduction) => 'Subsidy reduction (Art. 33(2) VAT Act)',
    };
  }
}
