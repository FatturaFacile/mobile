/// Translation tables of the module. Locales: `it-IT`, `it-CH`, `de-CH`, `fr-CH` and `en`; the app asks for a language, so
/// Italian resolves to `it-CH` when the country is Switzerland and to `it-IT` otherwise, German and French to their Swiss
/// tables (the Swiss legal vocabulary is shared by the tenants of both countries).
class FieldServiceStrings {
  const FieldServiceStrings._(this.tag, this._table);

  /// The locale tag in use; it is also the `locale` of the service report sent to the API.
  final String tag;
  final Map<FsmText, String> _table;

  static const List<String> locales = fsmReportLocales;

  /// `it-IT`, `it-CH`, `de-CH`, `fr-CH` or `en` for any [Locale].
  static String tagOf(Locale locale) => switch (locale.languageCode) {
    'it' => locale.countryCode == 'CH' ? 'it-CH' : 'it-IT',
    'de' => 'de-CH',
    'fr' => 'fr-CH',
    _ => 'en',
  };

  static FieldServiceStrings forLocale(Locale locale) {
    final String tag = tagOf(locale);
    return FieldServiceStrings._(tag, tables[tag]!);
  }

  static FieldServiceStrings of(BuildContext context) =>
      forLocale(Localizations.localeOf(context));

  String t(FsmText key) => _table[key]!;

  /// Label of a work order status.
  String status(FsmStatus status) => t(switch (status) {
    FsmStatus.dispatched => FsmText.statusDispatched,
    FsmStatus.enRoute => FsmText.statusEnRoute,
    FsmStatus.onSite => FsmText.statusOnSite,
    FsmStatus.inProgress => FsmText.statusInProgress,
    _ => FsmText.statusCompleted,
  });

  /// Label of a work type (`preventive`, `corrective`, `installation`, `warranty`); anything else is shown as sent.
  String workType(String workType) => switch (workType) {
    'preventive' => t(FsmText.typePreventive),
    'corrective' => t(FsmText.typeCorrective),
    'installation' => t(FsmText.typeInstallation),
    'warranty' => t(FsmText.typeWarranty),
    _ => workType,
  };

  /// Label of a checklist item code of the bundle; an unknown code is shown as sent.
  String checklistItem(String code) => switch (code) {
    'visual_inspection' => t(FsmText.itemVisualInspection),
    'lubrication' => t(FsmText.itemLubrication),
    'safety_devices' => t(FsmText.itemSafetyDevices),
    'functional_test' => t(FsmText.itemFunctionalTest),
    'fault_diagnosis' => t(FsmText.itemFaultDiagnosis),
    'repair_verified' => t(FsmText.itemRepairVerified),
    'installation_complete' => t(FsmText.itemInstallationComplete),
    'commissioning' => t(FsmText.itemCommissioning),
    'customer_briefing' => t(FsmText.itemCustomerBriefing),
    _ => code,
  };

  /// Message for an API field error code raised by the local checks ([FsmException.errors]).
  String error(String field, String code) => switch (field) {
    'work_performed_summary' => t(FsmText.errSummary),
    'labor_hours' => t(FsmText.errLabor),
    'travel_hours' => t(FsmText.errTravelHours),
    'travel_km' => t(FsmText.errTravelKm),
    'customer_signer_name' => t(FsmText.errSigner),
    'signature_svg' => t(FsmText.errSignature),
    'checklist' => t(FsmText.errChecklist),
    'meter_reading' || 'meter_reading_hours' || 'meter_reading_cycles' => t(
      code == 'invalid' ? FsmText.errGeneric : FsmText.errMeter,
    ),
    'work_order' || 'work_order_id' || 'status' => t(FsmText.errNotOpen),
    'caption' => t(FsmText.errCaption),
    'quantity' =>
      code == 'insufficient_stock'
          ? t(FsmText.insufficientStock)
          : t(FsmText.partQuantityInvalid),
    _ => t(FsmText.errGeneric),
  };

