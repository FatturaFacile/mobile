/// Replaces `{name}` placeholders in a label.
String fillBilling(String template, Map<String, Object> values) =>
    values.entries.fold(
      template,
      (String text, MapEntry<String, Object> entry) =>
          text.replaceAll('{${entry.key}}', '${entry.value}'),
    );
