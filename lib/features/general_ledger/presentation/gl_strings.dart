/// The locale tables, exposed so a unit test can check that each one defines every [GL].
const Map<String, Map<GL, String>> glLocaleTables = <String, Map<GL, String>>{
  'it': _it,
  'en': _en,
  'de': _de,
  'fr': _fr,
};

/// Localized labels of the general ledger screens; unknown languages fall back to English.
class GlStrings {
  const GlStrings(this.languageCode);

  final String languageCode;

  String call(GL key) =>
      (glLocaleTables[languageCode] ?? _en)[key] ?? _en[key] ?? '';

  String book(LedgerBook b) => switch (b) {
    LedgerBook.statutory => call(GL.bookStatutory),
    LedgerBook.tax => call(GL.bookTax),
    LedgerBook.ifrs => call(GL.bookIfrs),
  };

  String problem(JournalProblem p) => switch (p) {
    JournalProblem.descriptionMissing => call(GL.problemDescription),
    JournalProblem.tooFewLines => call(GL.problemLines),
    JournalProblem.lineWithoutAccount => call(GL.problemAccount),
    JournalProblem.lineWithoutAmount => call(GL.problemAmount),
    JournalProblem.lineOnBothSides => call(GL.problemBothSides),
    JournalProblem.unbalanced => call(GL.problemUnbalanced),
  };

  String status(JournalStatus s) => switch (s) {
    JournalStatus.draft => call(GL.statusDraft),
    JournalStatus.pendingApproval ||
    JournalStatus.approved ||
    JournalStatus.rejected => call(GL.statusPending),
    JournalStatus.posted => call(GL.statusPosted),
    JournalStatus.reversed => call(GL.statusReversed),
  };

  String syncState(JournalSyncState s) => switch (s) {
    JournalSyncState.localDraft => call(GL.stateLocal),
    JournalSyncState.queued => call(GL.stateQueued),
    JournalSyncState.synced => call(GL.stateSynced),
    JournalSyncState.rejected => call(GL.stateRejected),
  };

  String error(GlException e) => switch (e.kind) {
    GlErrorKind.invalid => e.detail.isEmpty ? call(GL.errorInvalid) : e.detail,
    GlErrorKind.forbidden => call(GL.errorForbidden),
    GlErrorKind.notFound => call(GL.errorNotFound),
    GlErrorKind.conflict => call(GL.errorConflict),
    GlErrorKind.offline => call(GL.errorOffline),
    GlErrorKind.unknown => call(GL.errorUnknown),
  };
}
