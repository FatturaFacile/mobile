/// Localized labels, money and dates of the receivables screens. Locales: `it-IT`, `it-CH`, `de-CH`, `fr-CH` and `en`;
/// Italian resolves to `it-CH` when the country is Switzerland and to `it-IT` otherwise, German and French to their
/// Swiss tables.
class ReceivablesStrings {
  const ReceivablesStrings._(this.tag, this._table);

  /// The locale tag in use.
  final String tag;
  final Map<RC, String> _table;

  static String tagOf(Locale locale) => switch (locale.languageCode) {
    'it' => locale.countryCode == 'CH' ? 'it-CH' : 'it-IT',
    'de' => 'de-CH',
    'fr' => 'fr-CH',
    _ => 'en',
  };

  static ReceivablesStrings forLocale(Locale locale) {
    final String tag = tagOf(locale);
    return ReceivablesStrings._(tag, tables[tag]!);
  }

  static ReceivablesStrings forTag(String tag) =>
      ReceivablesStrings._(tag, tables[tag] ?? tables['en']!);

  static ReceivablesStrings of(BuildContext context) =>
      forLocale(Localizations.localeOf(context));

  String t(RC key) => _table[key] ?? tables['en']![key] ?? '';

  /// A label with `{name}` placeholders filled in.
  String f(RC key, Map<String, Object> args) {
    String text = t(key);
    for (final MapEntry<String, Object> e in args.entries) {
      text = text.replaceAll('{${e.key}}', '${e.value}');
    }
    return text;
  }

  /// `1’234.50`, prefixed with the currency when there is one.
  String money(Money value, [String? currency]) =>
      value.format(tag, currency: currency);

  /// `31/12/2030` (it-IT), `31.12.2030` (Switzerland), `2030-12-31` (en).
  String date(DateTime? value) {
    if (value == null) {
      return '';
    }
    final String d = value.day.toString().padLeft(2, '0');
    final String m = value.month.toString().padLeft(2, '0');
    final String y = value.year.toString().padLeft(4, '0');
    return switch (tag) {
      'it-IT' => '$d/$m/$y',
      'en' => '$y-$m-$d',
      _ => '$d.$m.$y',
    };
  }

  /// Percentage with one decimal and the locale decimal mark.
  String percent(double value) {
    final String text = value.toStringAsFixed(1);
    return '${tag == 'it-IT' ? text.replaceAll('.', ',') : text}%';
  }

  /// `Current`, `1-30 days`, `121+ days`, from the bucket the server defined.
  String bucket(AgingBucketDef def) {
    if (def.isCurrent) {
      return t(RC.bucketCurrent);
    }
    if (def.to == null) {
      return f(RC.bucketOpenEnded, <String, Object>{'from': def.from});
    }
    return f(RC.bucketRange, <String, Object>{'from': def.from, 'to': def.to!});
  }

  String status(ItemStatus status) => switch (status) {
    ItemStatus.open || ItemStatus.unknown => t(RC.statusOpen),
    ItemStatus.partiallyPaid => t(RC.statusPartiallyPaid),
    ItemStatus.paid => t(RC.statusPaid),
    ItemStatus.overdue => t(RC.statusOverdue),
    ItemStatus.disputed => t(RC.statusDisputed),
    ItemStatus.writtenOff => t(RC.statusWrittenOff),
  };

  String allocationType(AllocationType type) => switch (type) {
    AllocationType.payment => t(RC.typePayment),
    AllocationType.creditNote => t(RC.typeCreditNote),
    AllocationType.debitAdjustment => t(RC.typeDebitAdjustment),
    AllocationType.writeOff => t(RC.typeWriteOff),
    AllocationType.discount => t(RC.typeDiscount),
  };

  String policy(ReactionPolicy policy) => switch (policy) {
    ReactionPolicy.warning => t(RC.policyWarning),
    ReactionPolicy.blockOrder => t(RC.policyBlockOrder),
    ReactionPolicy.blockDeliveryNote => t(RC.policyBlockDeliveryNote),
    ReactionPolicy.creditHold => t(RC.policyCreditHold),
    ReactionPolicy.unknown => '',
  };

  String overrideScope(OverrideScope scope) => switch (scope) {
    OverrideScope.order => t(RC.overrideScopeOrder),
    OverrideScope.deliveryNote => t(RC.overrideScopeDeliveryNote),
    OverrideScope.all || OverrideScope.unknown => t(RC.overrideScopeAll),
  };

  String rating(RiskRating rating) => switch (rating) {
    RiskRating.low => t(RC.riskLow),
    RiskRating.medium => t(RC.riskMedium),
    RiskRating.high => t(RC.riskHigh),
    RiskRating.critical => t(RC.riskCritical),
  };

  String draftIssue(DraftIssue issue) => switch (issue) {
    DraftIssue.amountInvalid => t(RC.errAmount),
    DraftIssue.exceedsOpen => t(RC.errExceedsOpen),
    DraftIssue.sourceRequired => t(RC.errSourceRequired),
    DraftIssue.exceedsSource => t(RC.errExceedsSource),
  };

  String error(ReceivablesException e) => switch (e.kind) {
    ReceivablesErrorKind.forbidden => t(RC.errorForbidden),
    ReceivablesErrorKind.notFound => t(RC.errorNotFound),
    ReceivablesErrorKind.offline => t(RC.errorOffline),
    ReceivablesErrorKind.invalid =>
      e.detail.isEmpty ? t(RC.errorInvalid) : e.detail,
    ReceivablesErrorKind.unknown => t(RC.errorUnknown),
  };

