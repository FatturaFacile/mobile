const Map<String, Map<PO, String>> purchaseOrderLocaleTables =
    <String, Map<PO, String>>{'it': _it, 'de': _de, 'fr': _fr, 'en': _en};

class PurchaseOrderStrings {
  const PurchaseOrderStrings(this.languageCode);

  final String languageCode;

  /// `de-CH` / `it_IT` / `FR` to `de` / `it` / `fr`.
  String get language => languageCode.split(RegExp('[-_]')).first.toLowerCase();

  String call(PO key) =>
      (purchaseOrderLocaleTables[language] ?? _en)[key] ?? _en[key] ?? '';

  /// A label with the `{n}` placeholder filled.
  String count(PO key, Object n) => call(key).replaceAll('{n}', '$n');

  String status(PurchaseOrder order) => switch (order.status) {
    PoStatus.draft => call(PO.statusDraft),
    PoStatus.pendingApproval => call(PO.statusPendingApproval),
    PoStatus.approved => call(PO.statusApproved),
    PoStatus.sent => call(PO.statusSent),
    PoStatus.confirmed => call(PO.statusConfirmed),
    PoStatus.partiallyReceived => call(PO.statusPartiallyReceived),
    PoStatus.received => call(PO.statusReceived),
    PoStatus.closed => call(PO.statusClosed),
    PoStatus.cancelled => call(PO.statusCancelled),
    PoStatus.unknown =>
      order.rawStatus.isEmpty ? call(PO.statusUnknown) : order.rawStatus,
  };

  String dropshipStatus(Dropship d) => switch (d.status) {
    DropshipStatus.pending => call(PO.dsPending),
    DropshipStatus.ddtIssued => call(PO.dsDdtIssued),
    DropshipStatus.partiallyDelivered => call(PO.dsPartiallyDelivered),
    DropshipStatus.delivered => call(PO.dsDelivered),
    DropshipStatus.unknown =>
      d.rawStatus.isEmpty ? call(PO.dsUnknown) : d.rawStatus,
  };

  String error(PoException e) => switch (e.kind) {
    PoErrorKind.offline => call(PO.errorOffline),
    PoErrorKind.forbidden => call(PO.errorForbidden),
    PoErrorKind.notFound => call(PO.errorNotFound),
    PoErrorKind.invalid => e.detail.isEmpty ? call(PO.errorInvalid) : e.detail,
    PoErrorKind.unknown => call(PO.errorUnknown),
  };
}
