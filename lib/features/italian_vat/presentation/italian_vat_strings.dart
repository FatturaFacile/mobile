/// The locale tables, exposed so a unit test can check that each one defines every [IV].
const Map<String, Map<IV, String>> italianVatLocaleTables =
    <String, Map<IV, String>>{'it': _it, 'en': _en, 'de': _de, 'fr': _fr};

/// Localized labels of the Italian VAT screens; unknown languages fall back to English, and a region tag (`de-CH`,
/// `it_IT`) selects its language.
class ItalianVatStrings {
  const ItalianVatStrings(this.languageCode);

  final String languageCode;

  /// `de-CH` / `it_IT` / `FR` to `de` / `it` / `fr`.
  String get language => languageCode.split(RegExp('[-_]')).first.toLowerCase();

  String call(IV key) =>
      (italianVatLocaleTables[language] ?? _en)[key] ?? _en[key] ?? '';

  String register(VatRegisterType type) => switch (type) {
    VatRegisterType.sales => call(IV.regSales),
    VatRegisterType.purchases => call(IV.regPurchases),
    VatRegisterType.receipts => call(IV.regReceipts),
    VatRegisterType.thirdPartyGoods => call(IV.regThirdParty),
  };

  String kind(IntentLetterKind kind) => switch (kind) {
    IntentLetterKind.singleOperation => call(IV.kindSingle),
    IntentLetterKind.upToAmount => call(IV.kindUpTo),
    IntentLetterKind.period => call(IV.kindPeriod),
  };

  String letterStatus(IntentLetterStatus status) => switch (status) {
    IntentLetterStatus.active => call(IV.statusActive),
    IntentLetterStatus.exhausted => call(IV.statusExhausted),
    IntentLetterStatus.expired => call(IV.statusExpired),
    IntentLetterStatus.revoked => call(IV.statusRevoked),
  };

  String plafond(PlafondResult result) => switch (result) {
    PlafondResult.ok => call(IV.plafondOk),
    PlafondResult.nearLimit => call(IV.plafondNear),
    PlafondResult.exceedsPlafond => call(IV.plafondExceeded),
    PlafondResult.expired => call(IV.plafondExpired),
    PlafondResult.notYetValid => call(IV.plafondNotYet),
    PlafondResult.revoked => call(IV.plafondRevoked),
    PlafondResult.missingProtocol => call(IV.plafondNoProtocol),
  };

  String draftIssue(IntentLetterDraftIssue issue) => switch (issue) {
    IntentLetterDraftIssue.customerMissing => call(IV.issueCustomer),
    IntentLetterDraftIssue.protocolFormat => call(IV.issueProtocol),
    IntentLetterDraftIssue.amountMissing => call(IV.issueAmount),
    IntentLetterDraftIssue.periodInverted => call(IV.issuePeriod),
  };

  String settlementStatus(LipeSettlement s) => s.paid
      ? call(IV.statusPaid)
      : switch (s.status) {
          'posted' => call(IV.statusPosted),
          _ => call(IV.statusDraft),
        };

  String signature(SignatureStatus status) => switch (status) {
    SignatureStatus.unsigned => call(IV.sigUnsigned),
    SignatureStatus.signed => call(IV.sigSigned),
    SignatureStatus.invalid => call(IV.sigInvalid),
  };

  String xsd(bool? valid) => switch (valid) {
    true => call(IV.xsdValid),
    false => call(IV.xsdInvalid),
    null => call(IV.xsdPending),
  };

  String reconciliation(ReconciliationState state) => switch (state) {
    ReconciliationState.reconciled => call(IV.reconciled),
    ReconciliationState.difference => call(IV.differenceFound),
    ReconciliationState.unknown => call(IV.reconUnknown),
  };

  String recipientKind(RecipientKind kind) => switch (kind) {
    RecipientKind.professional => call(IV.professional),
    RecipientKind.agent => call(IV.agent),
  };

  String f24(F24Status status) => switch (status) {
    F24Status.unpaid => call(IV.f24Unpaid),
    F24Status.partial => call(IV.f24Partial),
    F24Status.paid => call(IV.f24Paid),
  };

  String action(VatActionKind kind) => switch (kind) {
    VatActionKind.intentLetter => call(IV.actionLetter),
    VatActionKind.lipeGeneration => call(IV.actionLipe),
    VatActionKind.certificateGeneration => call(IV.actionCu),
  };

  String outcome(
    ActionOutcome outcome, {
    required IV queued,
    required IV sent,
    required IV rejected,
  }) => switch (outcome.status) {
    ActionStatus.queued => call(queued),
    ActionStatus.sent => call(sent),
    ActionStatus.rejected =>
      outcome.detail.isEmpty ? call(rejected) : outcome.detail,
  };

  String error(ItalianVatException e) => switch (e.kind) {
    ItalianVatErrorKind.forbidden => call(IV.errorForbidden),
    ItalianVatErrorKind.notFound => call(IV.errorNotFound),
    ItalianVatErrorKind.offline => call(IV.errorOffline),
    ItalianVatErrorKind.invalid =>
      e.detail.isEmpty ? call(IV.errorInvalid) : e.detail,
    ItalianVatErrorKind.unknown => call(IV.errorUnknown),
  };
}
